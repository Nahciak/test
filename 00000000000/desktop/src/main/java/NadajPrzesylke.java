    /**
     * Ustala szerokość etykiety ceny według najdłuższego opisu ceny, aby po wybraniu
     * "Sprawdź Cenę" okno dopasowane do kontrolek nie musiało zmieniać układu.
     */
    private void zarezerwujMiejsceNaCene() {
        FontMetrics metrykaCzcionki = etykietaCeny.getFontMetrics(etykietaCeny.getFont());
        int najwiekszaSzerokosc = metrykaCzcionki.stringWidth(etykietaCeny.getText());
        for (RodzajPrzesylki rodzaj : RodzajPrzesylki.values()) {
            najwiekszaSzerokosc = Math.max(najwiekszaSzerokosc, metrykaCzcionki.stringWidth(rodzaj.getOpisCeny()));
        }
        Dimension rozmiar = new Dimension(najwiekszaSzerokosc, etykietaCeny.getPreferredSize().height);
        etykietaCeny.setPreferredSize(rozmiar);
        etykietaCeny.setMinimumSize(rozmiar);
    }

    private void sprawdzCene() {
        RodzajPrzesylki rodzaj = wybranyRodzajPrzesylki();
        etykietaObrazu.setIcon(wczytajObraz(rodzaj.getNazwaObrazu()));
        etykietaCeny.setText(rodzaj.getOpisCeny());
    }

    private void zatwierdz() {
        String komunikat = WalidatorKoduPocztowego.sprawdz(poleKodPocztowy.getText());
        wyswietlaczKomunikatow.accept(komunikat);
    }

    private RodzajPrzesylki wybranyRodzajPrzesylki() {
        if (poleRadioList.isSelected()) {
            return RodzajPrzesylki.LIST;
        }
        if (poleRadioPaczka.isSelected()) {
            return RodzajPrzesylki.PACZKA;
        }
        return RodzajPrzesylki.POCZTOWKA;
    }

    private ImageIcon wczytajObraz(String nazwaPliku) {
        return new ImageIcon(getClass().getResource("/" + nazwaPliku));
    }

